import AppKit
import XCTest
@testable import FsyncMacCore

@MainActor
final class PasteboardWatcherTests: EngineTestCase {
    private func makeWatcher(_ pb: NSPasteboard, frontmost: String? = nil, _ sink: @escaping (PasteboardChange) -> Void) -> PasteboardWatcher {
        PasteboardWatcher(pasteboard: pb, frontmost: { frontmost }, onChange: sink)
    }

    func testPollReportsOnlyChanges() {
        let pb = scratchPasteboard()
        var seen: [PasteboardChange] = []
        let w = makeWatcher(pb) { seen.append($0) }
        XCTAssertFalse(w.poll())
        pb.clearContents(); pb.setString("one", forType: .string)
        XCTAssertTrue(w.poll())
        XCTAssertFalse(w.poll())
        XCTAssertEqual(seen.count, 1)
        XCTAssertEqual(seen[0].decision, .sync)
        XCTAssertTrue(seen[0].types.contains("public.utf8-plain-text"))
    }

    func testReadingContentDoesNotCountAsChange() {
        let pb = scratchPasteboard()
        pb.clearContents(); pb.setString("x", forType: .string)
        var count = 0
        let w = makeWatcher(pb) { _ in count += 1 }
        _ = pb.string(forType: .string); _ = pb.types
        XCTAssertFalse(w.poll())
        XCTAssertEqual(count, 0)
    }

    /// Real items carrying the marker types: nothing sensitive may be classified as sync.
    func testMarkedItemsAreSkipped() {
        let pb = scratchPasteboard()
        var decisions: [FilterDecision] = []
        let w = makeWatcher(pb) { decisions.append($0.decision) }
        for marker in [nil, SensitiveFilter.concealedType, SensitiveFilter.transientType, SensitiveFilter.autoGeneratedType,
                       SensitiveFilter.originType, nil] {
            pb.clearContents()
            let item = NSPasteboardItem()
            item.setString("secret-or-not", forType: .string)
            if let marker { item.setData(Data(), forType: NSPasteboard.PasteboardType(marker)) }
            pb.writeObjects([item])
            w.poll()
        }
        XCTAssertEqual(decisions, [.sync, .skip(.concealed), .skip(.transient), .skip(.autoGenerated), .skip(.ownWrite), .sync])
    }

    func testFrontmostDenylistedAppIsSkipped() {
        let pb = scratchPasteboard()
        var decision: FilterDecision?
        let w = makeWatcher(pb, frontmost: "com.1password.1password") { decision = $0.decision }
        pb.clearContents(); pb.setString("pw", forType: .string)
        w.poll()
        XCTAssertEqual(decision, .skip(.deniedApp("com.1password.1password")))
    }

    func testUpdatedFilterApplies() {
        let pb = scratchPasteboard()
        var decision: FilterDecision?
        let w = makeWatcher(pb, frontmost: "org.example.vault") { decision = $0.decision }
        w.update(filter: SensitiveFilter(userDenylist: ["org.example.vault"]))
        pb.clearContents(); pb.setString("x", forType: .string)
        w.poll()
        XCTAssertEqual(decision, .skip(.deniedApp("org.example.vault")))
    }

    func testTimerDetectsChangeAndStops() async {
        let pb = scratchPasteboard()
        var count = 0
        let w = makeWatcher(pb) { _ in count += 1 }
        w.start(fast: 0.02, idle: 0.02)
        XCTAssertTrue(w.isRunning)
        pb.clearContents(); pb.setString("a", forType: .string)
        await eventually("timer saw the change") { count == 1 }
        w.stop()
        XCTAssertFalse(w.isRunning)
        pb.clearContents(); pb.setString("b", forType: .string)
        try? await Task.sleep(nanoseconds: 150_000_000)
        XCTAssertEqual(count, 1, "stopped watcher stays silent")
    }

    func testStartIgnoresWhatWasAlreadyThere() async {
        let pb = scratchPasteboard()
        pb.clearContents(); pb.setString("old", forType: .string)
        var count = 0
        let w = makeWatcher(pb) { _ in count += 1 }
        pb.clearContents(); pb.setString("changed before start", forType: .string)
        w.start(fast: 0.02, idle: 0.02)
        try? await Task.sleep(nanoseconds: 150_000_000)
        w.stop()
        XCTAssertEqual(count, 0)
    }
}
