import Foundation

/// Why a pasteboard change is not synced. Only type names and the frontmost bundle id are looked at.
public enum SkipReason: Equatable, CustomStringConvertible {
    case ownWrite
    case concealed
    case transient
    case autoGenerated
    case deniedApp(String)

    public var description: String {
        switch self {
        case .ownWrite: return "own-write"
        case .concealed: return "concealed"
        case .transient: return "transient"
        case .autoGenerated: return "auto-generated"
        case .deniedApp(let id): return "denied-app:\(id)"
        }
    }
}

public enum FilterDecision: Equatable {
    case sync
    case skip(SkipReason)
}

/// Pure decision over pasteboard type names (nspasteboard.org convention) and the frontmost app.
public struct SensitiveFilter {
    public static let originType = "com.fsync.origin"
    public static let concealedType = "org.nspasteboard.ConcealedType"
    public static let transientType = "org.nspasteboard.TransientType"
    public static let autoGeneratedType = "org.nspasteboard.AutoGeneratedType"
    /// 1Password also writes its own marker next to the standard one.
    public static let onePasswordType = "com.agilebits.onepassword"

    public static let defaultDenylist: Set<String> = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.agilebits.onepassword-osx",
        "com.bitwarden.desktop", "com.apple.keychainaccess", "com.apple.Passwords",
    ]

    public var denylist: Set<String>

    public init(denylist: Set<String> = SensitiveFilter.defaultDenylist) { self.denylist = denylist }

    public func decide(types: [String], frontmostBundleId: String?) -> FilterDecision {
        let set = Set(types)
        if set.contains(Self.originType) { return .skip(.ownWrite) }
        if set.contains(Self.concealedType) || set.contains(Self.onePasswordType) { return .skip(.concealed) }
        if set.contains(Self.transientType) { return .skip(.transient) }
        if set.contains(Self.autoGeneratedType) { return .skip(.autoGenerated) }
        if let id = frontmostBundleId, denylist.contains(id) { return .skip(.deniedApp(id)) }
        return .sync
    }
}
