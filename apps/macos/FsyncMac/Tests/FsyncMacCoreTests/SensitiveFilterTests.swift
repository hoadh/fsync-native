import XCTest
@testable import FsyncMacCore

final class SensitiveFilterTests: XCTestCase {
    private let text = "public.utf8-plain-text"

    func testDecisions() {
        let f = SensitiveFilter()
        XCTAssertEqual(f.decide(types: [text], frontmostBundleId: nil), .sync)
        XCTAssertEqual(f.decide(types: [text], frontmostBundleId: "com.apple.Safari"), .sync)
        XCTAssertEqual(f.decide(types: [text, SensitiveFilter.concealedType], frontmostBundleId: nil), .skip(.concealed))
        XCTAssertEqual(f.decide(types: [SensitiveFilter.onePasswordType], frontmostBundleId: nil), .skip(.concealed))
        XCTAssertEqual(f.decide(types: [text, SensitiveFilter.transientType], frontmostBundleId: nil), .skip(.transient))
        XCTAssertEqual(f.decide(types: [text, SensitiveFilter.autoGeneratedType], frontmostBundleId: nil), .skip(.autoGenerated))
        XCTAssertEqual(f.decide(types: [text, SensitiveFilter.originType], frontmostBundleId: nil), .skip(.ownWrite))
    }

    func testBuiltInDenylistApplies() {
        let f = SensitiveFilter()
        for id in ["com.1password.1password", "com.bitwarden.desktop", "com.apple.keychainaccess"] {
            XCTAssertEqual(f.decide(types: [text], frontmostBundleId: id), .skip(.deniedApp(id)), id)
        }
    }

    func testUserDenylistIsAddedToBuiltIn() {
        let f = SensitiveFilter(userDenylist: ["org.example.vault"])
        XCTAssertEqual(f.decide(types: [text], frontmostBundleId: "org.example.vault"), .skip(.deniedApp("org.example.vault")))
        XCTAssertEqual(f.decide(types: [text], frontmostBundleId: "com.1password.1password"), .skip(.deniedApp("com.1password.1password")))
    }

    func testMarkerWinsOverAllowedApp() {
        XCTAssertEqual(SensitiveFilter().decide(types: [SensitiveFilter.concealedType], frontmostBundleId: "com.apple.Safari"),
                       .skip(.concealed))
    }

    func testUserTextOnlyForExplicitRefusals() {
        XCTAssertNil(SkipReason.ownWrite.userText)
        XCTAssertNotNil(SkipReason.concealed.userText)
        XCTAssertNotNil(SkipReason.deniedApp("x").userText)
    }
}
