import AppKit
import ClipSpikeCore

enum WatcherChecks {
    static func run(_ r: Report, cpuSeconds secs: Double) {
        changeDetection(r)
        filterTable(r)
        mixedStream(r)
        externalWriter(r)
        privacy(r)
        cpu(r, seconds: secs)
    }

    static func changeDetection(_ r: Report) {
        let pb = uniquePasteboard()
        var seen = 0
        let w = PasteboardWatcher(pasteboard: pb, frontmost: { nil }) { _ in seen += 1 }
        let idle = !w.poll()
        for i in 0..<5 { pb.clearContents(); pb.setString("t\(i)", forType: .string); w.poll() }
        r.check("watcher: no change -> no event", idle)
        r.check("watcher: 5 writes -> 5 events (poll between writes)", seen == 5, "seen=\(seen)")
        let before = seen
        _ = pb.string(forType: .string)
        w.poll()
        r.check("watcher: reading content does not bump changeCount", seen == before)
    }

    static func filterTable(_ r: Report) {
        let f = SensitiveFilter()
        let cases: [(String, [String], String?, FilterDecision)] = [
            ("plain text", ["public.utf8-plain-text"], nil, .sync),
            ("concealed (1Password/Keychain style)", ["public.utf8-plain-text", SensitiveFilter.concealedType], nil, .skip(.concealed)),
            ("transient", ["public.utf8-plain-text", SensitiveFilter.transientType], nil, .skip(.transient)),
            ("auto-generated", ["public.utf8-plain-text", SensitiveFilter.autoGeneratedType], nil, .skip(.autoGenerated)),
            ("own write marker", ["public.utf8-plain-text", SensitiveFilter.originType], nil, .skip(.ownWrite)),
            ("1Password legacy marker", [SensitiveFilter.onePasswordType], nil, .skip(.concealed)),
            ("denied frontmost app", ["public.utf8-plain-text"], "com.1password.1password", .skip(.deniedApp("com.1password.1password"))),
            ("allowed frontmost app", ["public.utf8-plain-text"], "com.apple.Safari", .sync),
        ]
        for (name, types, front, want) in cases {
            r.check("filter: \(name)", f.decide(types: types, frontmostBundleId: front) == want)
        }
    }

    /// Real pasteboard items carrying the marker types: nothing sensitive may reach `synced`.
    static func mixedStream(_ r: Report) {
        let pb = uniquePasteboard()
        var synced: [PasteboardChange] = []
        var skipped: [String] = []
        let w = PasteboardWatcher(pasteboard: pb, frontmost: { nil }) {
            if $0.decision == .sync { synced.append($0) } else if case .skip(let why) = $0.decision { skipped.append(why.description) }
        }
        func write(_ extra: String?) {
            pb.clearContents()
            let item = NSPasteboardItem()
            item.setString("secret-or-not", forType: .string)
            if let extra { item.setData(Data(), forType: NSPasteboard.PasteboardType(extra)) }
            pb.writeObjects([item])
            w.poll()
        }
        for extra in [nil, SensitiveFilter.concealedType, SensitiveFilter.transientType, SensitiveFilter.autoGeneratedType,
                      SensitiveFilter.originType, nil] { write(extra) }
        r.check("stream: 2 normal synced, 4 marked items skipped, 0 concealed captured",
                synced.count == 2 && skipped == ["concealed", "transient", "auto-generated", "own-write"],
                "synced=\(synced.count) skipped=\(skipped)")
    }

    /// A writer in another process (like any app copying) is seen by the timer-driven watcher.
    static func externalWriter(_ r: Report) {
        let pb = uniquePasteboard()
        var firstSeen: Date?
        let w = PasteboardWatcher(pasteboard: pb, frontmost: { nil }) { _ in firstSeen = firstSeen ?? Date() }
        w.start(fast: 0.15, idle: 1.0)
        let t0 = Date()
        let res = runChild(["write-text", pb.name.rawValue, "hello"], timeout: 10)
        pump(until: 3) { firstSeen == nil }
        w.stop()
        let latency = firstSeen.map { $0.timeIntervalSince(t0) }
        r.check("watcher: other-process write seen by adaptive timer", firstSeen != nil && res.json != nil,
                "latency incl. child start=\(latency.map(fmt) ?? "n/a")s")
        // Rapid writes: polling coalesces; the last state must still be visible (last wins).
        var events = 0
        let w2 = PasteboardWatcher(pasteboard: pb, frontmost: { nil }) { _ in events += 1 }
        w2.start(fixed: 0.3)
        for i in 0..<50 { pb.clearContents(); pb.setString("r\(i)", forType: .string) }
        pump(until: 1) { events == 0 }
        w2.stop()
        r.check("watcher: 50 rapid writes coalesce into >=1 event, last value readable",
                events >= 1 && pb.string(forType: .string) == "r49", "events=\(events)")
    }

    /// `accessBehavior` and `changeCount`/`types` are the privacy-relevant calls; none shows an alert here.
    static func privacy(_ r: Report) {
        let pb = NSPasteboard.general
        if #available(macOS 15.4, *) {
            let b = pb.accessBehavior
            r.info("privacy: NSPasteboard.general.accessBehavior (this process)", "\(b.rawValue) (0=default 1=ask 2=alwaysAllow 3=alwaysDeny)")
        }
        let c1 = pb.changeCount
        _ = pb.types
        r.check("privacy: changeCount + types read need no content access", pb.changeCount == c1)
    }

    /// Idle watcher cost on a quiet pasteboard (user+system CPU of this process / wall time).
    static func cpu(_ r: Report, seconds: Double) {
        for (label, fixed, idle) in [("fixed 300 ms", Optional(0.3), 1.0), ("adaptive idle 1 s", nil, 1.0)] {
            let pb = uniquePasteboard()
            let w = PasteboardWatcher(pasteboard: pb, frontmost: { nil }) { _ in }
            let c0 = cpuSeconds(), t0 = Date()
            w.start(fixed: fixed, idle: idle)
            RunLoop.current.run(until: Date().addingTimeInterval(seconds))  // one blocking run: no harness spinning
            w.stop()
            let pct = (cpuSeconds() - c0) / Date().timeIntervalSince(t0) * 100
            r.check("cpu: \(label) over \(Int(seconds)) s < 0.5%", pct < 0.5, "\(fmt(pct))% (\(w.polls) polls)")
        }
    }
}
